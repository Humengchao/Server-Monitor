import Foundation
import SwiftUI

public enum AppLanguage: String, CaseIterable, Identifiable, Sendable {
    case system, zh, en
    public var id: String { rawValue }
}

/// Two-language UI strings.
///
/// Hand-rolled rather than a `.strings`/String Catalog bundle because the app
/// is built by SwiftPM without Xcode's resource tooling, and because the
/// language is switchable at runtime rather than only at launch.
public final class Localization: ObservableObject {
    @Published public var language: AppLanguage {
        didSet { UserDefaults.standard.set(language.rawValue, forKey: Self.storageKey) }
    }

    private static let storageKey = "appLanguage"

    public init() {
        let stored = UserDefaults.standard.string(forKey: Self.storageKey)
        language = stored.flatMap(AppLanguage.init(rawValue:)) ?? .system
    }

    /// What `.system` means on this Mac. Read once: a process's preferred
    /// languages are fixed at launch, and `t()` runs for every label on every
    /// render — the CFBundle lookup behind `Locale.preferredLanguages` was
    /// showing up in the profile for a value that never changes.
    private let systemLanguage: AppLanguage =
        (Locale.preferredLanguages.first ?? "en").hasPrefix("zh") ? .zh : .en

    /// Resolved language: `.system` follows the user's preferred languages.
    public var resolved: AppLanguage {
        language == .system ? systemLanguage : language
    }

    public func t(_ key: String) -> String {
        guard let pair = Self.table[key] else {
            assertionFailure("missing localization key: \(key)")
            return key
        }
        return resolved == .zh ? pair.zh : pair.en
    }

    /// Single-placeholder interpolation, e.g. t("server.deleteConfirm", "web-1").
    public func t(_ key: String, _ argument: String) -> String {
        t(key).replacingOccurrences(of: "{}", with: argument)
    }

    /// Every key in the table, so a test can walk it. Exposed because a
    /// duplicate key traps inside the dictionary literal at first use — which
    /// is during app launch, not at build time.
    static var knownKeys: [String] { Array(table.keys) }

