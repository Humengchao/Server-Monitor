import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const read = name => readFileSync(resolve(root, 'shared/probes', name), 'utf8').replace(/\r\n/g, '\n');
const lines = text => text.split('\n').map(line => line.trim()).filter(line => line && !line.startsWith('#'));
const windows = lines(read('windows-metrics.ps1')).join('\n') + '\n';
const linux = lines(read('linux-metrics.txt'));
const values = Object.fromEntries(lines(read('probes.txt')).map(line => {
  const split = line.indexOf('=');
  if (split < 1) throw new Error(`Invalid probe: ${line}`);
  return [line.slice(0, split).trim(), line.slice(split + 1).trim()];
}));
const names = ['startClock', 'statFirst', 'statSecond', 'memInfo', 'loadAvg', 'netDev', 'diskStats', 'uptime', 'nproc', 'diskUsage', 'processes', 'hostInfo', 'gpu', 'docker', 'endClock'];
if (linux.length !== names.length) throw new Error('Linux probe contract changed: update section names and parser fixtures together');
const quote = JSON.stringify;
const header = '// Generated by shared/scripts/generate-probes.mjs. Edit shared/probes instead.\n';
const go = `${header}package services\n\nconst windowsMetricsScript = ${quote(windows)}\n\nvar sharedLinuxSections = map[string]string{\n${linux.map((line, i) => `\t${quote(names[i])}: ${quote(line)},`).join('\n')}\n}\n\nvar sharedProbeValues = map[string]string{\n${Object.entries(values).map(([key, value]) => `\t${quote(key)}: ${quote(value)},`).join('\n')}\n}\n`;
const swift = `${header}import Foundation\n\nenum SharedProbes {\n    static let windowsMetricsScript = ${quote(windows)}\n    static let linuxSections: [String] = [\n${linux.map(line => `        ${quote(line)},`).join('\n')}\n    ]\n    static let values: [String: String] = [\n${Object.entries(values).map(([key, value]) => `        ${quote(key)}: ${quote(value)},`).join('\n')}\n    ]\n}\n`;
let failed = false;
for (const [name, content] of [
  ['web/backend/internal/services/probes_generated.go', go],
  ['macos/Sources/ServerMonitorKit/Collect/SharedProbes.generated.swift', swift],
]) {
  const path = resolve(root, name);
  if (process.argv.includes('--check')) {
    let existing = '';
    try { existing = readFileSync(path, 'utf8').replace(/\r\n/g, '\n'); } catch {}
    // gofmt aligns map literals; whitespace outside string literals is not
    // part of the contract. Compare normalized lines without touching strings.
    const normalize = text => text.split('\n').map(line => line.replace(/^(\s*)/, '').replace(/:\s+(?=")/, ': ')).join('\n');
    if (normalize(existing) !== normalize(content)) { console.error(`Generated probes are stale: ${name}`); failed = true; }
  } else { mkdirSync(dirname(path), { recursive: true }); writeFileSync(path, content); }
}
if (failed) process.exitCode = 1;
